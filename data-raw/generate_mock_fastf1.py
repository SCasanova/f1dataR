"""Generate pickled, trimmed FastF1 sessions used to mock FastF1 in the tests.

Run MANUALLY by a maintainer with valid F1 credentials (never in CI), via
    Rscript data-raw/generate_mock_fastf1.R

Writes tests/testthat/fixtures/fastf1/session_<season>_<round>_<code>.pkl
"""
import pickle
import sys
from pathlib import Path

import fastf1
import pandas as pd

out_dir = Path(sys.argv[1])
cache_dir = Path(sys.argv[2])
out_dir.mkdir(parents=True, exist_ok=True)
cache_dir.mkdir(parents=True, exist_ok=True)
fastf1.Cache.enable_cache(str(cache_dir))

SEASON, ROUND = 2023, 1
DRIVERS = ["VER", "HAM", "ALO"]
SESSIONS = ["R", "Q"]
MAX_RACE_LAPS = 8  # keeps telemetry small


def trim(session):
    laps = session.laps
    laps = laps[laps["Driver"].isin(DRIVERS)]
    if session.name == "Race":
        # first laps plus each driver's fastest lap so pick_fastest() works
        fastest = laps.groupby("Driver")["LapTime"].idxmin().dropna().tolist()
        laps = laps[(laps["LapNumber"] <= MAX_RACE_LAPS) | laps.index.isin(fastest)]
    numbers = set(
        session.results.loc[session.results["Abbreviation"].isin(DRIVERS), "DriverNumber"]
    )
    session._laps = laps
    session._car_data = {k: v for k, v in session.car_data.items() if k in numbers}
    session._pos_data = {k: v for k, v in session.pos_data.items() if k in numbers}
    session._results = session.results[session.results["Abbreviation"].isin(DRIVERS)]
    return session


for code in SESSIONS:
    session = fastf1.get_session(SEASON, ROUND, code)
    session.load(laps=True, telemetry=True, weather=True, messages=False)
    session = trim(session)
    path = out_dir / f"session_{SEASON}_{ROUND}_{code}.pkl"
    with open(path, "wb") as f:
        pickle.dump(session, f, protocol=pickle.HIGHEST_PROTOCOL)
    print(f"Wrote {path} ({path.stat().st_size / 1e6:.2f} MB)")

with open(out_dir / "README.md", "w") as f:
    f.write(
        "Mock FastF1 sessions generated by `data-raw/generate_mock_fastf1.R`.\n\n"
        f"- fastf1 version: {fastf1.__version__}\n"
        f"- pandas version: {pd.__version__}\n"
        f"- sessions: {SEASON} round {ROUND}, {SESSIONS}; drivers {DRIVERS}\n"
        f"- generated: {pd.Timestamp.now().date()}\n"
    )
